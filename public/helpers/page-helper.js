'use strict';

let pageHelper = (function () {

    function setActivePage(page) {
        $('#app-navbar .nav-link').removeClass('active').removeAttr('aria-current');
        $('#app-navbar .nav-link[data-id="' + page + '"]').addClass('active').attr('aria-current', 'page');

        // The map page is full-bleed (no container, no footer).
        $('body').toggleClass('page-map', page === 'map');
    }

    // Bootstrap modal asking for confirmation. Resolves true/false.
    function confirm(options) {
        return new Promise(function (resolve) {
            let modal = $(
                '<div class="modal fade" tabindex="-1" aria-hidden="true">' +
                '  <div class="modal-dialog modal-dialog-centered">' +
                '    <div class="modal-content">' +
                '      <div class="modal-header">' +
                '        <h2 class="modal-title fs-5"></h2>' +
                '        <button type="button" class="btn-close" data-bs-dismiss="modal" aria-label="' + i18n.t('Затваряне') + '"></button>' +
                '      </div>' +
                '      <div class="modal-body"></div>' +
                '      <div class="modal-footer">' +
                '        <button type="button" class="btn btn-secondary" data-bs-dismiss="modal">' + i18n.t('Отказ') + '</button>' +
                '        <button type="button" class="btn ux-confirm"></button>' +
                '      </div>' +
                '    </div>' +
                '  </div>' +
                '</div>');

            let confirmed = false;

            modal.find('.modal-title').text(options.title);
            modal.find('.modal-body').text(options.body);
            modal.find('.ux-confirm')
                .addClass(options.danger ? 'btn-danger' : 'btn-primary')
                .text(options.confirmText || i18n.t('Потвърждение'))
                .on('click', function () {
                    confirmed = true;
                    instance.hide();
                });

            modal.on('hidden.bs.modal', function () {
                instance.dispose();
                modal.remove();
                resolve(confirmed);
            });

            $('body').append(modal);

            let instance = new bootstrap.Modal(modal[0]);
            instance.show();
        });
    }

    function formatBytes(bytes) {
        if (bytes === null || bytes === undefined) {
            return '';
        }

        if (bytes < 1024) {
            return bytes + ' B';
        }

        let units = ['KB', 'MB', 'GB'];
        let value = bytes;
        let unit = -1;

        do {
            value /= 1024;
            unit++;
        } while (value >= 1024 && unit < units.length - 1);

        return value.toLocaleString(i18n.locale, { maximumFractionDigits: value < 10 ? 1 : 0 }) + ' ' + units[unit];
    }

    // one / many are Bulgarian words, translated here: formatCount(3, 'файл', 'файла').
    function formatCount(count, one, many) {
        if (count === null || count === undefined) {
            return '';
        }

        return count.toLocaleString(i18n.locale) + ' ' + i18n.t(count === 1 ? one : many);
    }

    // SQLite "YYYY-MM-DD HH:MM:SS" (UTC) -> local date.
    function formatDate(value) {
        if (!value) {
            return '';
        }

        let date = moment.utc(value, 'YYYY-MM-DD HH:mm:ss');

        return date.isValid() ? date.local().format(i18n.dateFormat) : value;
    }

    // Copies text to the clipboard. navigator.clipboard needs HTTPS (or localhost), so plain-HTTP
    // LAN access falls back to execCommand; if that fails too, the text is shown to copy by hand.
    function copyText(text, successMessage) {
        let done = () => toastr.success(successMessage || i18n.t('Копирано.'));

        if (navigator.clipboard && window.isSecureContext) {
            navigator.clipboard.writeText(text).then(done, () => fallbackCopy(text, done));
        } else {
            fallbackCopy(text, done);
        }
    }

    function fallbackCopy(text, done) {
        // Inside an open Bootstrap modal the focus trap would steal focus from an element in <body>.
        let host = $(document.activeElement).closest('.modal')[0] || document.body;
        let input = $('<textarea class="visually-hidden"></textarea>').val(text).appendTo(host);

        input[0].focus();
        input[0].select();

        try {
            if (document.execCommand('copy')) {
                done();
            } else {
                throw new Error();
            }
        } catch (e) {
            toastr.info(i18n.t('Копирайте ръчно: {text}', { text: text }));
        }

        input.remove();
    }

    // One legend entry from map legend data ({ swatch, label, count, hidden }).
    // swatch is SVG markup generated by map.js from constant style definitions.
    function legendRow(entry, className) {
        let row = $('<li></li>').addClass(className).append(
            $('<span class="legend-swatch"></span>').html(entry.swatch),
            $('<span class="legend-label"></span>').text(entry.label),
            $('<span class="layer-count"></span>').text(entry.count)
        );

        if (entry.hidden) {
            row.addClass('legend-hidden').attr('title', i18n.t('Показва се при по-голямо приближение'));
            row.find('.legend-label').append($('<span class="legend-hint"></span>').text(' · ' + i18n.t('приближете')));
        }

        return row;
    }

    function slug(name) {
        return String(name).toLowerCase();
    }

    return {
        setActivePage: setActivePage,
        confirm: confirm,
        formatBytes: formatBytes,
        formatCount: formatCount,
        formatDate: formatDate,
        copyText: copyText,
        legendRow: legendRow,
        slug: slug
    };
}());
